// w32_locale_gen.cpp -- writes hook/w32_locale_tables.inc: this machine's Windows answers for the locale/string
// stand-ins (hook/w32_locale.cpp) -- code pages 1252 (the ANSI code page) and 437 (the OEM one) both ways, best fit
// included; the user default locale's GetLocaleInfoA strings; upper/lower case and character types over the BMP.
// Run once on the reference machine (en-US); the tables are checked in, and test/w32_kernel_test.cpp compares the
// stand-ins against the live API.
//   cl /nologo /EHsc /std:c++17 test\w32_locale_gen.cpp /Fe:test\build\w32_locale_gen.exe
//   test\build\w32_locale_gen.exe > hook\w32_locale_tables.inc
#define _CRT_SECURE_NO_WARNINGS
#include <windows.h>
#include <stdio.h>
#include <io.h>
#include <fcntl.h>
#include <stdint.h>
#include <string>
#include <vector>

static void sbcs(UINT cp, const char* name) {
    printf("// code page %u: byte -> UTF-16 (MultiByteToWideChar, flags 0)\n", cp);
    printf("static const uint16_t k_%s_to_u[256] = {", name);
    for (int b = 0; b < 256; b++) {
        char c = (char)b;
        WCHAR w = 0;
        MultiByteToWideChar(cp, 0, &c, 1, &w, 1);
        printf("%s0x%04x,", b % 12 ? " " : "\n    ", w);
    }
    printf("\n};\n");
    printf("// code page %u: bytes MB_ERR_INVALID_CHARS refuses (a bit each)\n", cp);
    uint32_t bad[8] = {};
    for (int b = 0; b < 256; b++) {
        char c = (char)b;
        WCHAR w = 0;
        if (!MultiByteToWideChar(cp, MB_ERR_INVALID_CHARS, &c, 1, &w, 1)) bad[b >> 5] |= 1u << (b & 31);
    }
    printf("static const uint32_t k_%s_invalid[8] = {", name);
    for (int i = 0; i < 8; i++) printf("0x%08x%s", bad[i], i < 7 ? ", " : "");
    printf("};\n");
    // UTF-16 -> byte with best fit (flags 0): every code unit that doesn't become the default character
    std::vector<std::pair<int, int>> m;
    for (int u = 1; u < 0x10000; u++) {
        if (u >= 0xd800 && u < 0xe000) continue;
        WCHAR w = (WCHAR)u;
        char out[4] = {};
        BOOL used = FALSE;
        int n = WideCharToMultiByte(cp, 0, &w, 1, out, 4, 0, &used);
        if (n == 1 && !used) m.push_back({u, (uint8_t)out[0]});
        else if (n != 1) fprintf(stderr, "cp %u: U+%04x gives %d bytes\n", cp, u, n);
    }
    printf("// code page %u: UTF-16 -> byte, best fit included (WideCharToMultiByte, flags 0); %d code units, sorted\n",
           cp, (int)m.size());
    printf("static const uint16_t k_%s_from_u[%d][2] = {", name, (int)m.size());
    for (size_t i = 0; i < m.size(); i++) printf("%s{0x%04x,0x%02x},", i % 6 ? " " : "\n    ", m[i].first, m[i].second);
    printf("\n};\n");
}

// n bytes as a C string literal (every byte that isn't plain ASCII escaped; the terminator included in n)
static void esc(const char* s, int n) {
    putchar('"');
    for (int i = 0; i < n; i++) {
        const unsigned char c = (unsigned char)s[i];
        if (c == '"' || c == '\\') printf("\\%c", c);
        else if (c < 0x20 || c >= 0x7f) printf("\\x%02x\"\"", c);
        else putchar(c);
    }
    putchar('"');
}

int main() {
    _setmode(_fileno(stdout), _O_BINARY);        // (LF line ends, as the sources)
    printf("// w32_locale_tables.inc -- GENERATED by test/w32_locale_gen.cpp on the reference machine (ACP %u, OEMCP %u,\n"
           "// user default LCID 0x%04x). Do not edit: regenerate.\n",
           GetACP(), GetOEMCP(), (unsigned)GetUserDefaultLCID());
    sbcs(1252, "cp1252");
    sbcs(437, "cp437");

    // GetLocaleInfoA(LOCALE_USER_DEFAULT, type): every type that answers
    printf("// GetLocaleInfoA(LOCALE_USER_DEFAULT, type) for each type that answers: n bytes, the terminator included\n"
           "// (LOCALE_FONTSIGNATURE is binary)\n");
    printf("struct LocaleString { uint32_t type; int n; const char* text; };\n");
    printf("static const LocaleString k_locale_strings[] = {\n");
    for (uint32_t t = 1; t < 0x2000; t++) {
        char buf[512];
        const int n = GetLocaleInfoA(LOCALE_USER_DEFAULT, t, buf, sizeof buf);
        if (n) {
            printf("    {0x%04x, %d, ", t, n);
            esc(buf, n - 1);
            printf("},\n");
        }
    }
    printf("};\n");

    // case maps: every BMP code unit that LCMapStringW changes
    for (int pass = 0; pass < 2; pass++) {
        const DWORD fl = pass ? LCMAP_LOWERCASE : LCMAP_UPPERCASE;
        std::vector<std::pair<int, int>> m;
        for (int u = 1; u < 0x10000; u++) {
            WCHAR w = (WCHAR)u, o[4] = {};
            int n = LCMapStringW(LOCALE_USER_DEFAULT, fl, &w, 1, o, 4);
            if (n == 1 && o[0] != w) m.push_back({u, o[0]});
            else if (n != 1) fprintf(stderr, "LCMapStringW %x U+%04x -> %d\n", fl, u, n);
        }
        printf("// LCMapStringW(LOCALE_USER_DEFAULT, %s) of single code units: the ones it changes (%d), sorted\n",
               pass ? "LCMAP_LOWERCASE" : "LCMAP_UPPERCASE", (int)m.size());
        printf("static const uint16_t k_%s[%d][2] = {", pass ? "lower" : "upper", (int)m.size());
        for (size_t i = 0; i < m.size(); i++) printf("%s{0x%04x,0x%04x},", i % 6 ? " " : "\n    ", m[i].first, m[i].second);
        printf("\n};\n");
    }

    // LCMAP_LINGUISTIC_CASING: where it differs from the plain mapping
    for (int pass = 0; pass < 2; pass++) {
        const DWORD fl = pass ? LCMAP_LOWERCASE : LCMAP_UPPERCASE;
        std::vector<std::pair<int, int>> m;
        for (int u = 1; u < 0x10000; u++) {
            WCHAR w = (WCHAR)u, o[4] = {}, l[4] = {};
            LCMapStringW(LOCALE_USER_DEFAULT, fl, &w, 1, o, 4);
            LCMapStringW(LOCALE_USER_DEFAULT, fl | LCMAP_LINGUISTIC_CASING, &w, 1, l, 4);
            if (l[0] != o[0]) m.push_back({u, l[0]});
        }
        printf("// LCMAP_LINGUISTIC_CASING | %s where it differs from the plain mapping (%d), sorted\n",
               pass ? "LCMAP_LOWERCASE" : "LCMAP_UPPERCASE", (int)m.size());
        printf("static const uint16_t k_ling_%s[%d][2] = {", pass ? "lower" : "upper", m.empty() ? 1 : (int)m.size());
        for (size_t i = 0; i < m.size(); i++) printf("%s{0x%04x,0x%04x},", i % 6 ? " " : "\n    ", m[i].first, m[i].second);
        if (m.empty()) printf("{0xffff, 0xffff}");
        printf("\n};\n");
    }

    // character types: runs of equal (CT_CTYPE1, CT_CTYPE2, CT_CTYPE3) over the BMP
    std::vector<WORD> t1(0x10000), t2(0x10000), t3(0x10000);
    std::vector<WCHAR> all(0x10000);
    for (int u = 0; u < 0x10000; u++) all[u] = (WCHAR)u;
    GetStringTypeW(CT_CTYPE1, all.data(), 0x10000, t1.data());
    GetStringTypeW(CT_CTYPE2, all.data(), 0x10000, t2.data());
    GetStringTypeW(CT_CTYPE3, all.data(), 0x10000, t3.data());
    std::vector<int> starts;
    for (int u = 0; u < 0x10000; u++)
        if (!u || t1[u] != t1[u - 1] || t2[u] != t2[u - 1] || t3[u] != t3[u - 1]) starts.push_back(u);
    printf("// GetStringTypeW over the BMP: runs {first code unit, CT_CTYPE1, CT_CTYPE2, CT_CTYPE3} (%d), sorted\n",
           (int)starts.size());
    printf("static const uint16_t k_ctype_runs[%d][4] = {", (int)starts.size());
    for (size_t i = 0; i < starts.size(); i++) {
        int u = starts[i];
        printf("%s{0x%04x,0x%03x,%d,0x%03x},", i % 4 ? " " : "\n    ", u, t1[u], t2[u], t3[u]);
    }
    printf("\n};\n");
    return 0;
}
